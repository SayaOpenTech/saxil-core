def idx(table: tuple[str, ...], value: str | None) -> int | None:
    if value is None:
        value = ""
    try:
        return table.index(value)
    except ValueError:
        return None


def at(table: tuple[str, ...], i: int) -> str:
    if i < 0 or i >= len(table):
        raise ValueError("enum oob")
    return table[i]
